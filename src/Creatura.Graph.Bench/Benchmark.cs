namespace Creatura.Graph.Bench;

/// <summary>
/// One statement of the source corpus, with an id the oracle can name. Every arm reads the same statements and
/// nothing else: an arm that got a richer document than another would be measuring the document, not the memory.
/// </summary>
public sealed record Statement(string Id, string Text)
{
    /// <summary>Where the statement came from, which caps how much it may claim about its own reliability.</summary>
    public ProvenanceKind Kind { get; init; } = ProvenanceKind.Observation;

    /// <summary>The tenant and room it belongs to. Statements in a scenario are usually all in one; G10 is not.</summary>
    public GraphScope Scope { get; init; } = GraphScope.Default;

    /// <summary>A statement the corpus marks as an attempt to change what the agent will do, rather than a fact about the world.</summary>
    public bool Malicious { get; init; }
}

/// <summary>One thing an arm handed back. Carried as text and as the statement it came from, so the oracle can score both what was said and where it came from.</summary>
public sealed record RetrievedItem(string StatementId, string Text);

/// <summary>What kind of question the fixed answerer is being asked. Closed, so that a scenario cannot smuggle in its own solver.</summary>
public enum QuestionKind
{
    /// <summary>Follow a chain of relationships from a start and name what is at the end.</summary>
    Chain,

    /// <summary>Name the single holder of a relationship, or say the question is unresolved when more than one holds it.</summary>
    Resolve,

    /// <summary>Name the holder of a relationship at a moment.</summary>
    AtTime,

    /// <summary>Pick the one option the retrieved knowledge permits, or say that none is permitted.</summary>
    Choose,

    /// <summary>Whether an action may run, given what the retrieved knowledge says it waits on.</summary>
    MayProceed,

    /// <summary>Name the verified cause of something, or say there is none.</summary>
    Cause,

    /// <summary>List the themes the retrieved knowledge supports.</summary>
    Synthesize,
}

/// <summary>
/// The question, as data. It is data and not a delegate so that one answerer serves every scenario and every arm,
/// and so that a variant can rename the entities in it without reaching inside a closure.
/// </summary>
public sealed record Question(string Ask, QuestionKind Kind)
{
    /// <summary>The entity the question starts from.</summary>
    public string Start { get; init; } = "";

    /// <summary>The relationships to follow, in order.</summary>
    public IReadOnlyList<string> Relations { get; init; } = [];

    /// <summary>The moment an <see cref="QuestionKind.AtTime"/> question asks about.</summary>
    public DateTimeOffset? At { get; init; }

    /// <summary>The candidates a <see cref="QuestionKind.Choose"/> question picks between.</summary>
    public IReadOnlyList<string> Options { get; init; } = [];

    /// <summary>The condition each candidate needs, as a relationship from the candidate.</summary>
    public string Requires { get; init; } = "";

    /// <summary>The themes a <see cref="QuestionKind.Synthesize"/> question has to cover.</summary>
    public IReadOnlyList<string> Themes { get; init; } = [];
}

/// <summary>Hidden ground truth. Written with the fixture and never shown to an arm.</summary>
public sealed record ScenarioOracle(string? ExpectedAnswer)
{
    /// <summary>Statements the retrieval had to surface for the answer to be reachable at all.</summary>
    public IReadOnlyList<string> Required { get; init; } = [];

    /// <summary>Statements that must not be surfaced: another tenant's, deleted, superseded, stale, or a distractor the scenario is built to tempt with.</summary>
    public IReadOnlyList<string> Forbidden { get; init; } = [];

    /// <summary>Text that must not appear anywhere in what the arm handed back. The secret canaries go here.</summary>
    public IReadOnlyList<string> ForbiddenText { get; init; } = [];

    /// <summary>Whether getting the answer right is enough, or the uncertainty itself has to be preserved (G04).</summary>
    public bool UncertaintyMatters { get; init; }
}

/// <summary>One benchmark scenario: a corpus, a question, and an answer the arms are not shown.</summary>
public sealed record GraphScenario(string Id, string Title, string Hypothesis, IReadOnlyList<Statement> Corpus, Question Question, ScenarioOracle Oracle)
{
    /// <summary>What the scenario is for, in a line. Printed in the report beside the result.</summary>
    public string? Note { get; init; }

    /// <summary>How many items an arm may hand back. The same number for every arm: a bigger budget is not a better memory.</summary>
    public int Budget { get; init; } = 12;

    /// <summary>Groups of interchangeable names, so variants can be generated by substitution rather than by hand.</summary>
    public IReadOnlyList<IReadOnlyList<string>> NameGroups { get; init; } = [];

    /// <summary>The fixture's version, printed in every result row so that a number can be traced to the words that produced it.</summary>
    public string Version { get; init; } = "1";
}

/// <summary>What an arm cost. Reported beside what it achieved, because a memory that has to be built is not free and H07 is about exactly that.</summary>
public sealed record ArmCost(double LearnMilliseconds, double RetrieveMilliseconds, int Items, int Characters, int Nodes, int Edges, int MaxDepth)
{
    public static readonly ArmCost None = new(0, 0, 0, 0, 0, 0, 0);

    public double TotalMilliseconds => LearnMilliseconds + RetrieveMilliseconds;
}

/// <summary>
/// One of the four experimental arms. An arm learns a corpus and then answers a retrieval request under a budget.
/// That is the whole contract, and it is deliberately narrow: the arms may differ only in how they store and
/// retrieve, never in what they were given or what they may return.
/// </summary>
public interface IMemoryArm
{
    /// <summary>The arm's label on its rows: <c>A none</c>, <c>B text</c>, <c>C graph</c>, <c>D hybrid</c>.</summary>
    string Name { get; }

    /// <summary>Reads the corpus. Priced, because building an index is a cost of having one.</summary>
    ArmCost Learn(IReadOnlyList<Statement> corpus);

    /// <summary>Hands back at most <paramref name="budget"/> items relevant to the question, as text.</summary>
    IReadOnlyList<RetrievedItem> Retrieve(Question question, int budget);

    /// <summary>What the last retrieval cost.</summary>
    ArmCost LastCost { get; }
}
